/* ============================================================================
 * 跨页「选一个东西带回去」的最小通道
 * ----------------------------------------------------------------------------
 * 场景：结算页要选地址 → 跳到地址簿 → 选完返回结算页。
 *
 * 为什么不用 uni.$emit / 事件通道：
 *   事件总线的时序是"谁先订阅谁收到"。地址簿在返回前发事件时，结算页可能
 *   还没完成重新订阅（页面在栈里不销毁，但订阅时机分散在各处），
 *   结果就是偶发地收不到 —— 偶发 bug 最难查。
 *
 * 这个通道反过来：**由发起方主动读取**，读一次即清空。
 * 时序上不存在竞态：地址簿只写，结算页在 onShow 里读，谁先谁后都对。
 * ==========================================================================*/

let pickedAddressId: number | null = null;

export function setPickedAddress(id: number): void {
  pickedAddressId = id;
}

/** 取出并清空。清空是必须的：否则下次进结算页会莫名其妙地"选中了上次那个地址" */
export function takePickedAddress(): number | null {
  const v = pickedAddressId;
  pickedAddressId = null;
  return v;
}
