/**
 * 面向**学生**的固定文案出口（服务端那一份在 `apps/server/src/ledger/copy.ts`）。
 *
 * 为什么要集中：
 *   §5.4 文案对照表把「库存不足」列为**禁止出现**。它只说了"不行"，
 *   没说"最多能买几件"、也没说"是哪个商品、哪一栋"—— 学生读完不知道该改什么，
 *   只能退出去重试一遍，然后再撞一次同一堵墙。
 *   而这句话在购物车面板、商品条目、商品详情、加购入口四个地方都要用，
 *   分散着写就一定会有一条漏改（漏掉的那条正好是学生最先遇到的那条）。
 *
 * 为什么不放进 `packages/` 跟服务端共用：
 *   两端各有一份词表是**有意的重复** —— 它们的语气本来就不同（服务端说"该商品在当前
 *   楼栋未上架"，学生端说"这件今天没上架"），硬合成一份会变成"取交集"，
 *   最后两边都说一句谁也不像的话。护栏（`scripts/check-error-copy.mjs`）负责
 *   保证两边都落地了对照表要求的关键词，这比共用文件更能防漏。
 */
export const CUSTOMER_COPY = {
  /** 加购触达上限（§5.4-3）：必须带上具体件数，学生才知道改到哪里 */
  stockLimit: (max: number) => `本栋最多能买 ${max} 件，已经到上限了`,

  /**
   * 售罄（§5.4-3）：必须点明**哪个商品、哪一栋**，并给出下一步。
   * `building` 传楼栋名；未知时退化成「本栋」。
   */
  soldOut: (product: string, building: string) =>
    `${product}在「${building || '本栋'}」已售罄，请移出后重新提交`,

  /** 重下单时部分商品放不回去：说清"少放了"而不是笼统的"失败" */
  reorderPartial: (n: number) => `${n} 件在本栋已售罄、少放了`,
} as const;
