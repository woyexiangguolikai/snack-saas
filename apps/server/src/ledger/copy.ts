/**
 * 中性文案的**唯一出处**。
 *
 * 为什么要有这个文件：
 *   账本相关的措辞一旦写成"你欠了平台的钱"，商户的感受就从"我该交服务费"
 *   变成"我被追债了" —— 这是产品判断，不是文案偏好。所以它必须是一条
 *   可机器审计的规则，而不是靠每个人写提示语时记得。
 *
 * 本文件是全仓库**唯一**允许出现禁用词的地方（因为要把它们列出来才能查）。
 * `npm run check:copy` 会扫描全库：禁用词只允许出现在本文件；
 * 出现在第二个文件就说明有人把它写进了对用户展示的字符串里 → 直接失败。
 */

